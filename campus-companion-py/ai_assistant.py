def generate_smart_study_advice(student_id: int) -> dict:

    """
    Generates personalized academic guidance and study plan locally
    using the student's active assignments, upcoming classes today,
    and optimal focus windows. Matches previous response format exactly.
    """
    import schedule
    import assignments
    import reminders

    conn = get_conn()
    student = conn.execute("SELECT name FROM student WHERE id = ?", (student_id,)).fetchone()
    student_name = student["name"] if student else "Student"
    conn.close()

    all_tasks = assignments.list_assignments(student_id)
    active_tasks = [t for t in all_tasks if t.get("status") != "COMPLETED"]
    today_classes = schedule.today(student_id)
    now_dt = clock.now(student_id)

    plan_lines = []

    # 1. Top Priority Task
    if active_tasks:
        nearest = active_tasks[0]
        days_left = nearest.get("days_left", 3)
        due_str = nearest.get("due_at", "")[:10]
        urgency_emoji = "🚨" if days_left <= 2 else "🎯"
        day_plural = "days" if days_left != 1 else "day"
        plan_lines.append(
            f"{urgency_emoji} **Top Priority**: Focus on **{nearest['title']}** — due in {days_left} {day_plural} ({due_str})."
        )
        if len(active_tasks) > 1:
            second = active_tasks[1]
            plan_lines.append(f"📋 **Secondary Task**: Begin preliminary research for **{second['title']}**.")
    else:
        plan_lines.append("🎉 **Top Priority**: All assignments are currently completed! Great job staying ahead.")

    # 2. Classes & Recommended Focus Window
    if today_classes and len(today_classes) > 0:
        class_names = [c["title"] for c in today_classes[:3]]
        plan_lines.append(f"📚 **Classes Today**: {', '.join(class_names)}.")
        plan_lines.append(
            "🕒 **Recommended Focus Window**: 90-minute study session after your afternoon classes to review notes while concepts are fresh."
        )
    else:
        plan_lines.append(
            "🕒 **Recommended Focus Window**: No scheduled classes today. Ideal day for deep project work and extended study sprints."
        )

    # 3. Actionable Study Pro-Tip
    plan_lines.append(
        "💡 **Study Pro-Tip**: Use the 50/10 study method — 50 minutes of distraction-free work followed by a 10-minute active break."
    )

    return {
        "studentName": student_name,
        "date": now_dt.strftime("%Y-%m-%d"),
        "advice": "\n\n".join(plan_lines),
        "engine": AI_ENGINE_NAME
    }
