def parse_intent_and_entities_with_gemini(student_id: int, utterance: str) -> dict | None:
    """
    Uses local NLP matching and semantic tokenization to extract intents and entities
    compatible with Amazon Alexa Skills Kit (ASK) and the web simulator.
    Operates 100% locally without external API keys.
    """

    text = utterance.lower().strip()
    tokens = tokenize_utterance(text)

    # Next Class Intent
    if any(phrase in text for phrase in ["next class", "next lecture", "where do i go", "what class next", "where next", "what's next"]):
        return {"intent": "NextClassIntent", "slots": {}, "direct_answer": None}

    # Upcoming Classes / Schedule Intent
    if any(phrase in text for phrase in ["schedule", "classes today", "upcoming classes", "timetable", "what do i have today", "my classes", "lectures today"]):
        day_val = None
        for d in ["monday", "tuesday", "wednesday", "thursday", "friday", "tomorrow"]:
            if d in text:
                day_val = d.capitalize()
                break
        return {"intent": "UpcomingClassesIntent", "slots": {"Day": day_val} if day_val else {}, "direct_answer": None}

    # Add Assignment Intent: e.g. "submit DBMS assignment within 5 days"
    if any(w in tokens for w in ["submit", "assignment", "homework", "project", "due"]) and any(w in tokens for w in ["within", "in", "days", "day", "add"]):
        days_match = re.search(r"(\d+)\s*days?", text)
        days = int(days_match.group(1)) if days_match else 5
        subject = "General"
        for s in ["DBMS", "OS", "AI", "Cloud", "Operating Systems", "Computer Networks", "Math", "Software Engineering"]:
            if s.lower() in text:
                subject = s
                break
        return {"intent": "AddAssignmentIntent", "slots": {"Subject": subject, "Days": days}, "direct_answer": None}

    # Complete Assignment Intent: e.g. "DBMS assignment is completed"
    if any(w in tokens for w in ["completed", "complete", "finished", "done"]):
        subject = None
        for s in ["Operating Systems", "Computer Networks", "DBMS", "OS", "AI", "Cloud"]:
            if re.search(r'\b' + re.escape(s.lower()) + r'\b', text):
                subject = s
                break
        return {"intent": "CompleteAssignmentIntent", "slots": {"Subject": subject} if subject else {}, "direct_answer": None}

    # Delete Assignment Intent
    if any(w in tokens for w in ["delete", "remove", "cancel"]):
        subject = None
        for s in ["Operating Systems", "Computer Networks", "DBMS", "OS", "AI", "Cloud"]:
            if re.search(r'\b' + re.escape(s.lower()) + r'\b', text):
                subject = s
                break
        return {"intent": "DeleteAssignmentIntent", "slots": {"Subject": subject} if subject else {}, "direct_answer": None}

    # Check Reminders Intent
    if any(w in tokens for w in ["reminder", "reminders", "pending", "deadline", "assessments"]):
        return {"intent": "CheckRemindersIntent", "slots": {}, "direct_answer": None}

    # Study Plan Intent
    if any(phrase in text for phrase in ["study plan", "advice", "how to study", "prioritize", "action plan", "mentor"]):
        return {"intent": "StudyPlanIntent", "slots": {}, "direct_answer": None}

    # General Academic Query
    spoken_answer = answer_student_query(student_id, utterance)
    # Strip markdown headers for spoken voice
    clean_spoken = re.sub(r"[#*`$]", "", spoken_answer).replace("\n\n", " ").strip()
    clean_spoken = clean_spoken[:200] + ("..." if len(clean_spoken) > 200 else "")

    return {
        "intent": "GeneralQueryIntent",
        "slots": {},
        "direct_answer": clean_spoken
    }


